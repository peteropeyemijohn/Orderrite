#!/usr/bin/env node
// Generates packages/shared/src/geo/countries.ts: every country and its
// international dialling code, from libphonenumber-js (the same library the
// API uses to check numbers) and English names from Node's Intl data.
// Run again only to refresh: node scripts/generate-country-list.mjs
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const require = createRequire(path.join(root, 'apps/api/package.json'));
const { getCountries, getCountryCallingCode } = require('libphonenumber-js/max');

const names = new Intl.DisplayNames(['en'], { type: 'region' });
const rows = getCountries()
  .map((code) => ({ code, name: names.of(code) ?? code, dialCode: `+${getCountryCallingCode(code)}` }))
  .sort((a, b) => a.name.localeCompare(b.name, 'en'));

const body = rows.map((r) => `  { code: '${r.code}', name: ${JSON.stringify(r.name)}, dialCode: '${r.dialCode}' },`).join('\n');
const file = `// GENERATED by scripts/generate-country-list.mjs. Do not edit by hand.
// Every country/territory with its international dialling code, for the phone
// number country picker. Countries Orderrite operates in come from the API and
// are shown first; this reference list lets anyone use their own number.

export interface DialCountry {
  /** ISO 3166-1 alpha-2, e.g. "NG" */
  code: string;
  name: string;
  /** e.g. "+234" */
  dialCode: string;
}

export const DIAL_COUNTRIES: readonly DialCountry[] = [
${body}
];
`;
writeFileSync(path.join(root, 'packages/shared/src/geo/countries.ts'), file);
console.log(`Wrote ${rows.length} countries`);
